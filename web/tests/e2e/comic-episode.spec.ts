import { cp, readFile } from 'node:fs/promises'
import path from 'node:path'
import { expect, test } from '../support/fixtures'
import { createAndOpenBook, createAgentChatSession, enablePlugin, setAgentChatApprovalMode, readProjectFile, saveProjectFile } from '../support/api'
import { modelControlURL, type E2EModelRequest } from '../support/model'

const source = process.env.DENOVA_TEST_COMIC_PLUGIN

test('a generic Agent saves unified references, resumes an interrupted episode and adopts it in bulk', async ({ page, request, browserDiagnostics }, testInfo) => {
  test.skip(!source, 'Set DENOVA_TEST_COMIC_PLUGIN to the index comic plugin directory')
  browserDiagnostics.allow(/console.error: Failed to load resource:.*404.*project-content\/file\?path=comic%2Fcomic.json/)
  const book = await createAndOpenBook(request, 'Comic episode acceptance')
  const initialSettings = await (await request.get('/api/settings')).json()
  const enabled = await request.patch('/api/settings', { data: { layer: 'user', base_revision: initialSettings.revisions.user, changes: { agent_tools: { ide: { todo: true } } } } })
  expect(enabled.ok(), await enabled.text()).toBe(true)
  await cp(source!, path.join(book.workspace, 'comic-plugin-source'), { recursive: true })
  await cp(path.resolve(source!, '../skills/comic-creation'), path.join(book.workspace, 'skills/comic-creation'), { recursive: true })
  const linked = await request.post('/api/platform/manage/development/link', { data: { kind: 'plugin', projectId: book.projectId, relativePath: 'comic-plugin-source' } })
  expect(linked.ok(), await linked.text()).toBe(true)
  const development = await linked.json()
  const checked = await request.get(`/api/platform/manage/development/${development.developmentId}/check`)
  expect(checked.ok(), await checked.text()).toBe(true)
  const candidate = await checked.json()
  const installed = await request.post('/api/platform/manage/packages/install', { data: { candidateId: candidate.candidateId, grants: candidate.manifest.permissions.required } })
  expect(installed.ok(), await installed.text()).toBe(true)
  await enablePlugin(request, candidate.manifest.id)
  const loreURL = `/api/projects/${book.projectId}/book/lore/items`
  const lore = await request.post(loreURL, { data: { id: 'hero', name: '固定主角', type: 'character', content: 'COMIC_FROZEN_CHARACTER wears a red scarf.', enabled: true } })
  expect(lore.ok(), await lore.text()).toBe(true)
  const fixture = await readFile(new URL('../fixtures/comic-page.png', import.meta.url))
  const upload = await request.post(`${loreURL}/hero/materials/upload`, { multipart: { file: { name: 'character.png', mimeType: 'image/png', buffer: fixture } } })
  expect(upload.ok(), await upload.text()).toBe(true)
  const character = await upload.json()
  const cover = await request.post(`${loreURL}/hero/materials`, { data: { op: 'cover', asset_id: character.resolved_materials[0].id } })
  expect(cover.ok(), await cover.text()).toBe(true)
  const session = await createAgentChatSession(request, book.projectId, 'Episode generation')
  await setAgentChatApprovalMode(request, book.projectId, session.id, 'full_access')
  const sessionKey = `nova.writingAgent.activeSession.v1:${encodeURIComponent('plugin:index.comic-studio/studio')}:${book.projectId}`
  await page.addInitScript(({ key, id }) => {
    localStorage.setItem('nova:mode', 'plugin:index.comic-studio/studio')
    if (!localStorage.getItem(key)) localStorage.setItem(key, id)
  }, { key: sessionKey, id: session.id })
  await page.setViewportSize({ width: 1600, height: 1000 })
  await page.goto('/')
  const studio = page.frameLocator('iframe[title="插件界面"]')
  const agent = page.locator('#plugin-page-agent')
  const composer = agent.getByRole('textbox')
  await studio.getByRole('button', { name: '新分话', exact: true }).first().click()
  await studio.getByRole('button', { name: '新页面', exact: true }).first().click()
  await studio.getByRole('button', { name: '图像模型', exact: true }).click()
  await studio.getByRole('menuitemradio', { name: 'E2E image model', exact: true }).click()
  await page.getByRole('button', { name: '参考图', exact: true }).click()
  await expect(studio.getByRole('button', { name: '上传参考图', exact: true })).toBeEnabled()
  await studio.locator('#upload').setInputFiles({ name: 'watercolor-style.png', mimeType: 'image/png', buffer: fixture })
  await expect(studio.locator('[data-reference]')).toHaveCount(1)
  await studio.getByRole('button', { name: '关闭', exact: true }).click()
  await composer.fill('/comic-creation 参考主角资料与水彩画风图，生成三页整话。 E2E_RUNTIME_COMIC_EPISODE_START')
  await agent.locator('[data-action="send"]').click()
  await expect.poll(async () => (await (await request.get(`${modelControlURL}/control/status`)).json()).delayed_waiting_by_marker.E2E_COMIC_EPISODE_HOLD).toBe(1)
  await expect(studio.getByRole('status', { name: /整话进度/ })).toContainText('已生成 1/3')
  await agent.getByRole('button', { name: '中断 AI 执行', exact: true }).click()
  await request.post(`${modelControlURL}/control/release`, { data: { marker: 'E2E_COMIC_EPISODE_HOLD' } })
  const comic = JSON.parse((await readProjectFile(request, book.projectId, 'comic/comic.json')).content)
  const episode = comic.episodes[0]
  expect(episode.pages).toHaveLength(3)
  const pagePath = (id: string) => `comic/pages/${id}/page.json`
  const readPage = async (id: string) => JSON.parse((await readProjectFile(request, book.projectId, pagePath(id))).content)
  const initial = await Promise.all(episode.pages.map((entry: { id: string }) => readPage(entry.id)))
  expect(initial.map(item => item.results.length)).toEqual([1, 0, 0])
  for (const item of initial) {
    expect(item.script.modelId).toBe('e2e-image')
    expect(item.script.references).toEqual(initial[0].script.references)
    expect(JSON.stringify(item.script.references)).toContain('COMIC_FROZEN_CHARACTER')
    expect(item.script.references[0].asset.path).toMatch(/^comic\/assets\/references\//)
    expect(item.script.references[1].asset.path).toMatch(/^comic\/assets\/references\//)
  }
  await page.reload()
  await expect(studio.getByRole('status', { name: /整话进度/ })).toContainText('已生成 1/3')
  await page.screenshot({ path: testInfo.outputPath('episode-interrupted-dark.png'), fullPage: true })
  const changedLore = await request.put(`${loreURL}/hero`, { data: { enabled: true, type: 'character', name: '固定主角', importance: 'major', tags: [], brief_description: '', keywords: [], load_mode: 'auto', content: 'COMIC_CHANGED_CHARACTER now wears a blue coat.' } })
  expect(changedLore.ok(), await changedLore.text()).toBe(true)
  const settings = await (await request.get('/api/settings')).json()
  const newModel = await request.patch('/api/settings', { data: { layer: 'user', base_revision: settings.revisions.user, changes: { image_api_profiles: [...settings.user.image_api_profiles, { id: 'episode-alternate', name: 'Episode alternate', endpoint_id: 'e2e-image', model: 'denova-e2e-image' }] } } })
  expect(newModel.ok(), await newModel.text()).toBe(true)
  await studio.getByRole('button', { name: '图像模型', exact: true }).click()
  await studio.getByRole('menuitemradio', { name: 'Episode alternate', exact: true }).click()
  // Lose local result materialization after a successful receipt. Recovery must
  // reuse the receipt even in a fresh Session, without another paid submission.
  initial[0].results = []
  initial[0].jobs[0].status = 'running'
  await saveProjectFile(request, book.projectId, pagePath(initial[0].id), JSON.stringify(initial[0]))
  const resumed = await createAgentChatSession(request, book.projectId, 'Episode continuation')
  await setAgentChatApprovalMode(request, book.projectId, resumed.id, 'full_access')
  await page.evaluate(({ key, id }) => localStorage.setItem(key, id), { key: sessionKey, id: resumed.id })
  await page.reload()
  await composer.fill('/comic-creation 继续剩余页面，保留已保存脚本。 E2E_RUNTIME_COMIC_EPISODE_CONTINUE')
  const continuation = page.waitForRequest(candidate => candidate.method() === 'POST' && candidate.url().endsWith(`/api/projects/${book.projectId}/agent-chat/chat`))
  await agent.locator('[data-action="send"]').click()
  expect((await continuation).postDataJSON().session_id).toBe(resumed.id)
  await expect(agent.getByText('整话已生成：3/3，尚未采用。', { exact: true })).toBeVisible()
  const completed = await Promise.all(episode.pages.map((entry: { id: string }) => readPage(entry.id)))
  for (const item of completed) {
    expect(item.results).toHaveLength(1)
    expect(item.results[0].modelId).toBe('e2e-image')
    expect(item.currentId).toBeNull()
    expect(item.script.references).toEqual(initial[0].script.references)
  }
  expect(completed[0].results[0].id).toBe(initial[0].jobs[0].commandId)
  expect((await (await request.get(`${modelControlURL}/control/status`)).json()).request_counts.E2E_COMIC_EPISODE_IMAGE).toBe(3)
  const imageRequest = await (await request.get(`${modelControlURL}/control/captured-request?marker=E2E_COMIC_EPISODE_IMAGE`)).json()
  expect(imageRequest.prompt).toContain('COMIC_FROZEN_CHARACTER')
  expect(imageRequest.prompt).not.toContain('COMIC_CHANGED_CHARACTER')
  expect(imageRequest.images).toHaveLength(2)
  await expect(studio.getByRole('status', { name: /整话进度/ })).toContainText('已生成 3/3')
  await composer.fill('/comic-creation 采用整话全部候选。 E2E_RUNTIME_COMIC_EPISODE_ADOPT')
  await agent.locator('[data-action="send"]').click()
  await expect(agent.getByText('整话已采用：3/3。', { exact: true })).toBeVisible()
  await expect(studio.getByRole('status', { name: /整话进度/ })).toContainText('已采用 3/3')
  for (const entry of episode.pages) {
    const item = await readPage(entry.id)
    expect(item.currentId).toBe(item.results[0].id)
    expect(item.results).toHaveLength(1)
  }
  const captured = await (await request.get(`${modelControlURL}/control/runtime-requests?marker=E2E_RUNTIME_COMIC_EPISODE_CONTINUE`)).json() as E2EModelRequest[]
  expect(JSON.stringify(captured[0].messages)).toContain('# Skill: comic-creation')
  const calls = captured.flatMap(turn => turn.messages.flatMap(message => message.tool_calls ?? []))
  expect(calls.some(call => call.function?.name === 'plugin_comic_render' && JSON.parse(call.function.arguments || '{}').action === 'recover')).toBe(true)
  expect(calls.some(call => call.function?.name === 'todo')).toBe(true)
  await page.screenshot({ path: testInfo.outputPath('episode-adopted-dark.png'), fullPage: true })
  const appearance = await (await request.get('/api/settings')).json()
  const light = await request.patch('/api/settings', { data: { layer: 'user', base_revision: appearance.revisions.user, changes: { theme: 'light' } } })
  expect(light.ok(), await light.text()).toBe(true)
  await page.reload()
  await expect(studio.locator('html')).toHaveAttribute('data-theme', 'light')
  await expect(studio.getByRole('status', { name: /整话进度/ })).toContainText('已采用 3/3')
  await expect(studio.locator('#pageImage')).toBeVisible()
  await expect.poll(() => studio.locator('#pageImage').evaluate(image => (image as HTMLImageElement).naturalWidth)).toBeGreaterThan(0)
  await page.screenshot({ path: testInfo.outputPath('episode-adopted-light.png'), fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  await studio.getByRole('button', { name: '展开分话与分页', exact: true }).click()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await expect(studio.getByRole('status', { name: /整话进度/ })).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('episode-mobile-light.png'), fullPage: true })
  const locale = await (await request.get('/api/settings')).json()
  const english = await request.patch('/api/settings', { data: { layer: 'user', base_revision: locale.revisions.user, changes: { language: 'en-US' } } })
  expect(english.ok(), await english.text()).toBe(true)
  await page.setViewportSize({ width: 1600, height: 1000 })
  await page.reload()
  const englishStudio = page.frameLocator('iframe[title="Plugin view"]')
  await expect(englishStudio.getByRole('status', { name: /Episode progress/ })).toContainText('Generated 3/3')
  await expect(englishStudio.getByRole('status', { name: /Episode progress/ })).toContainText('Adopted 3/3')
  await expect(englishStudio.locator('#pageImage')).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('episode-english-light.png'), fullPage: true })
})
